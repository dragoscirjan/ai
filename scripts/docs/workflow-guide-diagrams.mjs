const node = (id, lane, col, label, skill, sublabel, type = "backend") => ({
  id,
  lane,
  col,
  label: label === skill ? `/${skill}` : label,
  skill,
  sublabel,
  type,
});
const edge = (from, to, label, role = "main", variant = "default") => ({
  id: `${from}-to-${to}`,
  from,
  to,
  ...(label ? { label } : {}),
  role,
  variant,
});
const lane = (id, label, exception = false) => ({
  id,
  label,
  ...(exception ? { variant: "exception" } : {}),
});
