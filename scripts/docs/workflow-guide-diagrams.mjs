export function guideDiagram(guide, repository, sources) {
  const definition = definitions[guide.id];
  if (!definition) throw new Error(`Missing primary workflow diagram: ${guide.id}`);
  return {
    schema_version: 2,
    diagram_type: "workflow",
    meta: {
      title: guide.title,
      locale: "en",
      quality_profile: "showcase",
      output: `.docs-artifacts/archify/${guide.id}.html`,
      repository,
      legend: {
        entries: {
          backend: { label: "Guided work" },
          security: { label: "Decision or approval" },
          external: { label: "Input or handoff" },
        },
      },
    },
    lanes: definition.lanes,
    mainPath: definition.mainPath,
    nodes: definition.nodes.map(({ skill, ...item }) => ({
      ...item,
      icon: item.type === "security" ? "decision" : "none",
      sources: sources(skill),
    })),
    edges: definition.edges,
    semanticChecks: {
      allowedRoots: definition.roots,
      allowedTerminals: definition.terminals,
      requiredEdges: definition.edges
        .filter((item) => item.role === "return" || item.variant === "security")
        .map(({ from, to }) => ({ from, to })),
    },
    cards: definition.cards,
  };
}
